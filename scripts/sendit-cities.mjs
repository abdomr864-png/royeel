// Writes src/lib/cities.ts from Sendit's import file (liste-des-colis.xlsx,
// downloaded from app.sendit.ma). Its "Ville" column only accepts the
// names of its "Liste des villes" sheet, so the shop offers exactly those.
// Run again when Sendit changes its file:
//   node scripts/sendit-cities.mjs path/to/liste-des-colis.xlsx
import { readFileSync, writeFileSync } from 'node:fs'
import { inflateRawSync } from 'node:zlib'

const path = process.argv[2]
if (!path) throw new Error('Usage: node scripts/sendit-cities.mjs path/to/liste-des-colis.xlsx')
const files = unzip(readFileSync(path))
const text = (name) => {
  const f = files.get(name)
  if (!f) throw new Error(`${name} missing: is this Sendit's liste-des-colis.xlsx?`)
  return f.toString('utf8')
}
const decode = (s) =>
  s
    .replace(/&amp;/g, '&')
    .replace(/&apos;/g, "'")
    .replace(/&quot;/g, '"')
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')

const strings = [...text('xl/sharedStrings.xml').matchAll(/<si>([\s\S]*?)<\/si>/g)].map((m) =>
  decode([...m[1].matchAll(/<t[^>]*>([^<]*)<\/t>/g)].map((t) => t[1]).join('')),
)

// The sheet called "Liste des villes", through the workbook's relationships.
const sheetId = text('xl/workbook.xml').match(/<sheet name="Liste des villes"[^>]*r:id="([^"]+)"/)?.[1]
if (!sheetId) throw new Error('No "Liste des villes" sheet')
const target = text('xl/_rels/workbook.xml.rels').match(new RegExp(`Id="${sheetId}"[^>]*Target="([^"]+)"|Target="([^"]+)"[^>]*Id="${sheetId}"`))
const sheet = text(`xl/${(target[1] ?? target[2]).replace(/^\/?xl\//, '')}`)

const names = [
  ...new Set(
    [...sheet.matchAll(/<c r="A\d+"([^>]*)>\s*<v>([^<]*)<\/v>/g)]
      .map((m) => (/t="s"/.test(m[1]) ? strings[Number(m[2])] : decode(m[2])))
      .map((s) => s.replace(/\s+/g, ' ').trim())
      .filter(Boolean),
  ),
].sort((a, b) => a.localeCompare(b, 'fr', { sensitivity: 'base' }))
if (names.length < 100) throw new Error(`Only ${names.length} cities found`)

const today = new Date().toISOString().slice(0, 10)
const file = `// Places Sendit delivers to, spelled exactly as in the "Liste des villes"
// of its import file (liste-des-colis.xlsx), which refuses any other spelling.
// Generated by scripts/sendit-cities.mjs on ${today}: do not edit by hand.
export const CITIES: readonly string[] = [
${names.map((n) => `  ${JSON.stringify(n)},`).join('\n')}
]
`
writeFileSync('src/lib/cities.ts', file)
console.log(`${names.length} cities written to src/lib/cities.ts`)

// Minimal zip reader (stored and deflated entries), enough for an .xlsx.
function unzip(buf) {
  const out = new Map()
  let end = buf.length - 22
  while (end >= 0 && buf.readUInt32LE(end) !== 0x06054b50) end--
  if (end < 0) throw new Error('Not a zip file')
  let p = buf.readUInt32LE(end + 16)
  const count = buf.readUInt16LE(end + 10)
  for (let i = 0; i < count; i++) {
    const method = buf.readUInt16LE(p + 10)
    const size = buf.readUInt32LE(p + 20)
    const nameLen = buf.readUInt16LE(p + 28)
    const extraLen = buf.readUInt16LE(p + 30)
    const commentLen = buf.readUInt16LE(p + 32)
    const local = buf.readUInt32LE(p + 42)
    const name = buf.toString('utf8', p + 46, p + 46 + nameLen)
    const start = local + 30 + buf.readUInt16LE(local + 26) + buf.readUInt16LE(local + 28)
    const data = buf.subarray(start, start + size)
    out.set(name, method === 8 ? inflateRawSync(data) : data)
    p += 46 + nameLen + extraLen + commentLen
  }
  return out
}

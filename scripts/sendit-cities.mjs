// Writes src/lib/cities.ts from the districts of the Sendit account (the list
// on https://app.sendit.ma/districts), through the Sendit API. Needs the API
// keys in .env.local (never committed):
//   SENDIT_PUBLIC_KEY=...
//   SENDIT_SECRET_KEY=...
// Run again when Sendit adds places: node scripts/sendit-cities.mjs
import { writeFileSync } from 'node:fs'

try {
  process.loadEnvFile('.env.local')
} catch {}
const { SENDIT_PUBLIC_KEY: publicKey, SENDIT_SECRET_KEY: secretKey } = process.env
if (!publicKey || !secretKey) throw new Error('Add SENDIT_PUBLIC_KEY and SENDIT_SECRET_KEY to .env.local')
const API = 'https://app.sendit.ma/api/v1'

const login = await fetch(`${API}/login`, {
  method: 'POST',
  headers: { 'Content-Type': 'application/json', Accept: 'application/json' },
  body: JSON.stringify({ public_key: publicKey, secret_key: secretKey }),
})
const auth = await login.json().catch(() => ({}))
const token = auth?.data?.token ?? auth?.token
if (!login.ok || !token) throw new Error(`Sendit login failed (${login.status}): ${auth?.message ?? 'no token'}`)

const districts = []
for (let page = 1; page < 500; page++) {
  const res = await fetch(`${API}/districts?page=${page}`, {
    headers: { Authorization: `Bearer ${token}`, Accept: 'application/json' },
  })
  if (!res.ok) throw new Error(`Sendit answered ${res.status} on page ${page}`)
  const body = await res.json()
  // Laravel pagination, sometimes wrapped in { data: { data: [...] } }.
  const pageData = Array.isArray(body.data) ? body : (body.data ?? body)
  const rows = pageData.data ?? []
  districts.push(...rows)
  const last = pageData.last_page ?? pageData.meta?.last_page
  if (!rows.length || (last && page >= last) || (!last && !pageData.next_page_url)) break
}
if (districts.length < 100) throw new Error(`Only ${districts.length} districts received`)

const clean = (s) => String(s ?? '').replace(/\s+/g, ' ').trim()
const names = [...new Set(districts.map((d) => clean(d.name)).filter(Boolean))].sort((a, b) =>
  a.localeCompare(b, 'fr', { sensitivity: 'base' }),
)

// Arabic names, kept only when a single place has that name.
const byArabic = new Map()
for (const d of districts) {
  const ar = clean(d.arabic_name)
  if (ar) byArabic.set(ar, [...(byArabic.get(ar) ?? []), clean(d.name)])
}
const arabic = Object.fromEntries(
  names.flatMap((n) => {
    const ar = clean(districts.find((d) => clean(d.name) === n)?.arabic_name)
    return ar && byArabic.get(ar).length === 1 ? [[n, ar]] : []
  }),
)

const today = new Date().toISOString().slice(0, 10)
const file = `// Places Sendit delivers to, spelled as in its districts list
// (https://app.sendit.ma/districts), so orders reach it as they are.
// Generated by scripts/sendit-cities.mjs on ${today}: do not edit by hand.
export const CITIES: readonly string[] = [
${names.map((n) => `  ${JSON.stringify(n)},`).join('\n')}
]

// Arabic name of each place, when Sendit gives one that no other place shares.
export const CITIES_AR: Readonly<Record<string, string>> = {
${Object.entries(arabic)
  .map(([n, ar]) => `  ${JSON.stringify(n)}: ${JSON.stringify(ar)},`)
  .join('\n')}
}
`
writeFileSync('src/lib/cities.ts', file)
console.log(`${names.length} places (${Object.keys(arabic).length} with an Arabic name) written to src/lib/cities.ts`)

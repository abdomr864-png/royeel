// Writes src/lib/cities.ts from the list of places Ozon Express delivers to.
// Run again when Ozon adds cities: node scripts/ozon-cities.mjs
import { writeFileSync } from 'node:fs'

const res = await fetch('https://api.ozonexpress.ma/cities')
if (!res.ok) throw new Error(`Ozon Express answered ${res.status}`)
const { CITIES } = await res.json()

const names = [
  ...new Set(
    Object.values(CITIES)
      .map((c) => String(c.NAME).replace(/\s+/g, ' ').trim())
      .filter(Boolean),
  ),
].sort((a, b) => a.localeCompare(b, 'fr', { sensitivity: 'base' }))

const today = new Date().toISOString().slice(0, 10)
const file = `// Places Ozon Express delivers to, spelled as in its system so orders can be
// passed to it as they are. Generated by scripts/ozon-cities.mjs on ${today}
// from https://api.ozonexpress.ma/cities: do not edit by hand.
export const CITIES: readonly string[] = ${JSON.stringify(names, null, 2).replace(/"/g, "'").replace(/\\'/g, '’')}
`
writeFileSync('src/lib/cities.ts', file)
console.log(`${names.length} cities written to src/lib/cities.ts`)
